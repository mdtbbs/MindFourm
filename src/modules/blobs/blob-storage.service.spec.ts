import { createHash, randomUUID } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import { BlobStorageService } from './blob-storage.service';

describe('BlobStorageService', () => {
  let root: string;
  let storage: BlobStorageService;

  const key = () => `blobs/default/${'a'.repeat(32)}/${randomUUID()}`;

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'mindfourm-blobs-'));
    storage = new BlobStorageService(
      { get: () => undefined } as any,
      { getCached: (name: string) => name === 'blobs_storage_path' ? root : null } as any,
    );
  });

  afterEach(async () => { await rm(root, { recursive: true, force: true }); });

  it('writes verified bytes and reports the stored size', async () => {
    const objectKey = key();
    const bytes = Buffer.from('generic blob content');
    const sha256 = createHash('sha256').update(bytes).digest('hex');

    await storage.writeObject(objectKey, Readable.from(bytes), bytes.length, sha256, 1024);

    expect(await storage.statObject(objectKey)).toEqual({ exists: true, size_bytes: bytes.length });
    expect(await storage.verifyObject(objectKey, bytes.length, sha256, 1024)).toBe(true);
    expect(await readFile(join(root, ...objectKey.split('/')))).toEqual(bytes);
  });

  it('discards bytes that do not match the declared size or checksum', async () => {
    const bytes = Buffer.from('mismatched');
    const oversize = key();
    await expect(storage.writeObject(oversize, Readable.from(bytes), 2, '0'.repeat(64), 2))
      .rejects.toMatchObject({ code: 'BLOB_FILE_TOO_LARGE' });
    expect((await storage.statObject(oversize)).exists).toBe(false);

    const badSum = key();
    await expect(storage.writeObject(badSum, Readable.from(bytes), bytes.length, '0'.repeat(64), 1024))
      .rejects.toMatchObject({ code: 'BLOB_UPLOAD_CHECKSUM_MISMATCH' });
    expect((await storage.statObject(badSum)).exists).toBe(false);

    // A short body is caught as a size mismatch rather than a checksum failure,
    // because the caller's declared length is what the row will record.
    const short = key();
    await expect(storage.writeObject(short, Readable.from(bytes), bytes.length + 5, createHash('sha256').update(bytes).digest('hex'), 1024))
      .rejects.toMatchObject({ code: 'BLOB_UPLOAD_SIZE_MISMATCH' });
    expect((await storage.statObject(short)).exists).toBe(false);
  });

  it('refuses object keys that were not generated by this service', async () => {
    for (const objectKey of [
      '../escape',
      'blobs/default/' + 'a'.repeat(32) + '/../../escape',
      'cloud-saves/42/' + randomUUID(),
      'blobs/default/' + 'a'.repeat(31) + '/' + randomUUID(),
      '/etc/passwd',
    ]) {
      await expect(storage.statObject(objectKey)).rejects.toMatchObject({ code: 'BLOB_STORAGE_UNAVAILABLE' });
    }
  });

  it('reports a missing object instead of throwing, and deletes idempotently', async () => {
    const objectKey = key();
    expect(await storage.statObject(objectKey)).toEqual({ exists: false });
    expect(await storage.verifyObject(objectKey, 1, 'a'.repeat(64), 1024)).toBe(false);
    await expect(storage.openObject(objectKey)).rejects.toMatchObject({ code: 'BLOB_STORAGE_UNAVAILABLE' });
    await storage.deleteObject(objectKey);
  });

  it('rejects verification when the stored file changed after it was written', async () => {
    const objectKey = key();
    const bytes = Buffer.from('original');
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    await storage.writeObject(objectKey, Readable.from(bytes), bytes.length, sha256, 1024);

    await writeFile(join(root, ...objectKey.split('/')), Buffer.from('tampered'));
    expect(await storage.verifyObject(objectKey, bytes.length, sha256, 1024)).toBe(false);
  });

  it('requires an absolute, normalized, non-root storage path', () => {
    const relative = new BlobStorageService({ get: () => undefined } as any, { getCached: () => 'relative/path' } as any);
    expect(relative.isConfigured()).toBe(false);
    const rooted = new BlobStorageService({ get: () => undefined } as any, { getCached: () => '/' } as any);
    expect(rooted.isConfigured()).toBe(false);
    expect(storage.isConfigured()).toBe(true);
  });
});
